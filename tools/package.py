"""生成干净的发布包：只含 exe 和使用说明，不含任何个人数据。

⚠️ 为什么需要它：程序运行后会在 exe 同级的 `data\` 目录里存
   - config.json —— 含你的 DeepSeek API Key
   - astock.db —— 你的全部对话历史、策略、知识库、长期记忆

   如果直接把 `dist` 整个文件夹压缩发出去，这些都会一起泄露。
   这个脚本只挑 exe 打包，从根上避免误发。

用法：python tools/package.py
产物：发布/A股选股v2.0.zip  +  发布/A股选股v2.0/（解压好的同名文件夹）
"""

from __future__ import annotations

import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import VERSION_LABEL  # noqa: E402

EXE = ROOT / "dist" / "astock-agent.exe"
OUT_DIR = ROOT / "发布"
RELEASE_NAME = f"A股选股{VERSION_LABEL}"
OUT_ZIP = OUT_DIR / f"{RELEASE_NAME}.zip"
OUT_FOLDER = OUT_DIR / RELEASE_NAME

USAGE_TEXT = f"""============================================================
 A股智能选股助手 {VERSION_LABEL} —— 使用说明
============================================================

【怎么用】
  1. 双击 astock-agent.exe
     程序会自己启动本地服务并自动打开浏览器
     （首次启动需要解压几秒，请耐心等一下）

  2. 第一次用，点左下角「设置」，填两样东西：
       · DeepSeek API Key —— 在 platform.deepseek.com 申请
       · 通达信 vipdoc 目录 —— 一般会自动找到，找不到才需要手填

  3. 点顶栏「刷新数据」建立行情缓存（第一次要等一会儿）

  4. 之后直接在对话框里用大白话描述就行，例如：
       "找今天放量上涨、量比大于 2 的股票"
       "在我自选股里找量比大于 1 的"
       "今天市场整体怎么样？"

============================================================
 {VERSION_LABEL} 的几个主要功能
============================================================

【一、对话选股】
  用大白话描述条件，助手自动转成筛选并给出结果表格。
  也可以直接问数据状态、个股详情、K 线走势。

【二、自选策略（左下角「自选策略」）】
  把常看的选股条件存成一条策略，之后对话里说
  "用我的放量上涨策略选股" 就能直接跑。
  · 支持新建 / 编辑 / 搜索 / 删除 / 试跑
  · 也可以让助手帮你总结一套条件存进去
  · 策略里可以勾选「只看我的自选股」

【三、策略回测（策略列表里点「回测」）★重点】
  用历史数据模拟这个策略实际交易一遍，看它到底能不能赚钱。

  回测按真实交易约束计算，不做美化：
    · 信号次日开盘买入（不用当日收盘价，避免偷看未来）
    · 一字涨停买不进、一字跌停卖不出
    · T+1、停牌不交易
    · 计入佣金 0.025%（最低 5 元）与卖出印花税 0.05%

  结果包含：总收益、最大回撤、胜率、盈亏比、净值曲线、逐笔交易明细，
  并且【一定附上同期大盘基准做对照】——收益为正不等于策略有效，
  要看有没有跑赢基准。

【四、回测可信度 ★这个结果值不值得信】
  每次回测结束，结果页最上面会给出「可信度」——不是打分，是一份清单：

    可信度 · 偏低
      可信度偏低：样本外验证这一项没过关，结论不能作为依据。
      ✓ 交易笔数      303 笔，样本量充足
      ✓ 回测区间      244 个交易日（约 1 年以上）
      ✗ 样本外验证    未通过：样本内赚钱、样本外亏钱 —— 典型的过拟合
      · 参数稳定性    没做过参数扫描，不知道结果对参数是否敏感
      ✓ 收益集中度    最大单笔盈利占总盈利 2%，比较分散
      ✗ 相对基准      跑输沪深300 14.7 个百分点——没有超额价值
      ✓ 成交可执行性  因一字涨停没买进 0 次（占 0%），可执行性好

  共检查八项：交易笔数、回测区间、样本外验证、参数稳定性、
              收益集中度、相对基准、成交可执行性、数据质量。

  ★ 重点：【只做过单次回测的，可信度最高只能到「中等」】（会标注"已封顶"）。
    因为单次回测是样本内结果，只能说明「历史上是这样」，
    不能说明「将来也这样」。想让可信度上台阶，就得做样本外验证。

【五、样本外验证 ★判断策略真假的关键】
  把区间切成几段：前一段调参、后一段拿【没见过的数据】检验，滚动推进。
  如果样本内赚钱、样本外亏钱，说明这组参数是过拟合的，不能上实盘。
  还会自动给出结论等级（可信 / 存疑 / 过拟合）。

  另有「参数扫描」：同一批信号换多组止盈止损/持仓天数各跑一遍，
  看结果是否稳定。参数差一点结果就天差地别 = 碰巧凑出来的。

【六、交易计划（决定什么时候卖）】
  光有买入条件没法回测，所以每条策略都带一套卖出规则：
    · 最多持有 N 个交易日
    · 止损线 / 止盈线
    · 条件卖出：可从预设里挑（跌破均线、单日跌幅、量比、
      连跌、死叉、浮盈回落），也可以自己写表达式，
      例如：收盘 < MA10 且 量比 < 0.8
    · 最多同时持有几只、单只仓位占比

【七、知识库（左下角「知识库」）】
  把自己的交易纪律、选股流程等文档导进去，助手回答时会引用，
  并注明出处。【没有导入任何文档时，助手不会给出任何建议】，
  从机制上避免它凭空编。

【八、通达信自选股（左下角「自选股」）】
  直接读取你在通达信里的自选股（只读，不会改动你的通达信）。
  可以在对话里限定"只在我自选股里筛"。

【九、用量与余额】
  左下角实时显示 DeepSeek 余额和今日花费。

============================================================
【关于数据准确性】
============================================================
  · 通达信存的是【不复权】价格。股票除权除息（送转、分红）后价格会跳变，
    例如 10送10 会显示成一根 -50% 的巨阴线。不处理的话，回测会把它当成
    真实暴跌而触发止损，均线/涨跌幅/创新高这些指标在除权日附近也会算错。

    通达信的股本变迁文件是加密格式，解析不了，所以本程序用【涨跌停】作判据：
    A 股有涨跌停限制，任何超过限额的单日跳变必然是除权，据此自动做前复权。
    实测全市场 5251 只里有 410 只（7.8%）存在这类跳变，处理后可降到 0.9%，
    剩下的都是合法的无涨跌幅限制日（次新股上市初期、长期停牌复牌）。

  · 程序保证「实时选股」和「回测」用的指标口径【完全一致】——
    有 14 个用例在全市场 5183 只上逐日比对，结果必须完全相同。

============================================================
【依赖什么】
  · 通达信电脑版，并已下载/刷新过盘后数据（只读它的日线，不联网抓行情）
  · 一个 DeepSeek API Key（对话、回测解读要用，按量计费）

【数据存在哪】
  存在 exe 旁边的 data 文件夹里：API Key、对话历史、策略、知识库、行情缓存。
  想彻底重置，删掉 data 文件夹即可。整个文件夹拷走 = 连记录一起搬走。

【回测速度】
  回测要扫描全市场历史数据，用多进程并行（默认 4 个进程）。
  近 1 年约 6 秒，近 3 年约 20 秒。
  若某些安全软件拦截子进程导致变慢，可设环境变量 ASTOCK_WORKERS=1 关闭并行。

【说明】
  · 只做选股研究与策略验证，不构成任何投资建议，不涉及交易
  · 数据来自本地通达信日线，可能滞后于最新交易日
  · 回测结果基于历史数据，历史表现不代表将来收益
  · 程序只用 Python 标准库，不需要另装 Python 或任何运行库

============================================================
"""


def main() -> int:
    if not EXE.is_file():
        print(f"找不到 {EXE}")
        print("请先运行 build.cmd 生成 exe，再运行本脚本。")
        return 1

    OUT_DIR.mkdir(exist_ok=True)
    if OUT_ZIP.exists():
        OUT_ZIP.unlink()
    if OUT_FOLDER.exists():
        shutil.rmtree(OUT_FOLDER, ignore_errors=True)

    with zipfile.ZipFile(OUT_ZIP, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.write(EXE, "astock-agent.exe")
        archive.writestr("使用说明.txt", USAGE_TEXT)

    # 同时放一份解压好的文件夹，方便直接双击（和上一版保持一致）
    OUT_FOLDER.mkdir(parents=True, exist_ok=True)
    shutil.copy2(EXE, OUT_FOLDER / "astock-agent.exe")
    (OUT_FOLDER / "使用说明.txt").write_text(USAGE_TEXT, encoding="utf-8")

    size_mb = OUT_ZIP.stat().st_size / 1024 / 1024
    print(f"已生成发布包：{OUT_ZIP}")
    print(f"大小：{size_mb:.1f} MB")
    print(f"同时生成文件夹：{OUT_FOLDER}")
    print("内容：astock-agent.exe + 使用说明.txt")
    print("检查：不含 data 目录，不含 API Key，不含任何对话记录。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
